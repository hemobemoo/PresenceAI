"""The anchors document of a rubric (docs/rubric/<ID>_ANCHORS.md).

Generated from the rubric and its thresholds, so the document the supervisor reads is exactly
what the app uses. `tests/unit/test_rubric.py` fails when the committed document is stale.
This is a developer document in English, not app text.
"""

from __future__ import annotations

from presenceai.rubric.loader import RubricThresholds, anchor_text, fill
from presenceai.schemas.rubric import Condition, LevelAnchor, Rubric

_OPS = {">=": "≥", "<=": "≤"}


def _condition(c: Condition, t: RubricThresholds) -> str:
    if c.threshold is None:
        return f"`{c.measure}` = yes"
    return f"`{c.measure}` {_OPS[c.op]} {t.values[c.threshold]:g} (`{c.threshold}`)"


def arabic_status(rubric: Rubric, anchor: LevelAnchor) -> str:
    """Which of a level's conditions can be computed for Arabic (FINAL_04 §5, ADR 0016)."""
    if not anchor.conditions:
        return "default when any measure is computable"
    arabic = [c.measure for c in anchor.conditions if "ar" in rubric.measures[c.measure].languages]
    if not arabic:
        return "not measured (missing, not low)"
    if len(arabic) == len(anchor.conditions):
        return "measured"
    return "only " + ", ".join(f"`{m}`" for m in arabic)


def review_markdown(rubric: Rubric, t: RubricThresholds) -> str:
    title = rubric.id.upper().split("_")[0]
    out = [
        f"# {title} rubric anchors",
        "",
        f"Rubric `{rubric.id}` version {rubric.version}, status **{rubric.status}**, reviewed by "
        f"the supervisor. Thresholds: **{t.status}** (re-estimate after E5/E6), see "
        f"{t.decided_in}.",
        "",
        "> Generated by `uv run python scripts/render_rubric_review.py` from "
        f"`resources/rubrics/{rubric.id}.yaml` and `configs/rubric.yaml`. Do not edit by hand.",
        "",
        "## How to read the anchors",
        "",
        "- Five dimensions follow the AAC&U VALUE Oral Communication rubric, each with four "
        "levels: " + ", ".join(f"{n} {rubric.scale[n]}" for n in (4, 3, 2, 1)) + ".",
        "- Every anchor describes **observable behaviour with a number**. A level is reached when "
        "all of its computable conditions hold; the dimension gets the highest level reached; "
        "level 1 is the default.",
        "- **A missing measure is missing, never low.** A measure that cannot be computed (camera "
        "off, no time limit, Arabic content, unreliable punctuation) is dropped from the "
        "conditions. A dimension with no computable measure is reported as not measurable, never "
        "as level 1.",
        "- Skill score for the adaptive engine: y = (level − 1) / 3, so 0, 0.33, 0.67, 1.",
        "- **Every number is provisional** and is re-estimated after E5/E6. Numbers from the plan "
        "(FINAL_04) are the opening 20 %, the closing 15 % and the first 2 sentences.",
        "- Introduction, conclusion, thesis and transition cues are **lexicon matches**, not an "
        "understanding of meaning or structure.",
        '- "Left out" lists the parts of the VALUE wording that no rule can observe. They are '
        "not scored by rules. A language-model check may comment on some of them, only with "
        "consent (d), only with a quoted transcript span, never overriding a rule-based level, "
        "and never as a numeric level (ADR 0017).",
        "",
    ]
    for d in rubric.dimensions:
        out += [
            f"## {d.name}",
            "",
            f"VALUE dimension: {d.value_dimension}. Feeds the skills: "
            + ", ".join(f"`{s}`" for s in d.skills)
            + ".",
            "",
            "| Level | Anchor (observable) | Conditions | Arabic |",
            "|---|---|---|---|",
        ]
        for a in d.levels:
            conds = "<br>".join(_condition(c, t) for c in a.conditions) or "default"
            out.append(
                f"| {a.level} {rubric.scale[a.level]} | {anchor_text(a, t)} | {conds} "
                f"| {arabic_status(rubric, a)} |"
            )
        if d.left_out:
            out += ["", "Left out (not observable by rules): " + "; ".join(d.left_out) + "."]
        out.append("")
    out += [
        "## Arabic wording (draft)",
        "",
        "The Arabic anchors translate the reviewed English wording. They are a draft for a "
        "native-speaker review (ADR 0016 open item 4), with the same numbers. The content "
        "dimensions are not measured in Arabic (FINAL_04 §5), but their wording is shown.",
        "",
    ]
    for d in rubric.dimensions:
        out += [f"### {d.name} — {d.name_ar}", "", "| Level | Arabic anchor |", "|---|---|"]
        for a in d.levels:
            name = rubric.scale_ar[a.level]
            out.append(f"| {a.level} {name} | {anchor_text(a, t, 'ar')} |")
        out.append("")
    out += ["## Definitions", ""]
    out += [f"- **{name}**: {fill(text, t)}" for name, text in rubric.definitions.items()]
    out += [
        "",
        "## Measures",
        "",
        "| Measure | Status | Needs | Languages | Description |",
        "|---|---|---|---|---|",
    ]
    for key, m in rubric.measures.items():
        status = m.status if m.planned_in is None else f"planned ({m.planned_in})"
        langs = ", ".join(m.languages)
        out.append(f"| `{key}` | {status} | {m.requires} | {langs} | {m.description} |")
    out += [
        "",
        "## Source and licence",
        "",
        rubric.attribution,
        "",
        f"Source copy: {rubric.source.copy_url} (SHA-256 `{rubric.source.copy_sha256}`).",
    ]
    if rubric.source.note:
        out += ["", rubric.source.note]
    return "\n".join(out) + "\n"

"""The review document for a rubric draft (docs/rubric/<ID>_ANCHORS_FOR_REVIEW.md).

Generated from the rubric and its thresholds, so the document the supervisor reads is exactly
what the app uses. `tests/unit/test_rubric.py` fails when the committed document is stale.
This is a developer document in English, not app text.
"""

from __future__ import annotations

from presenceai.rubric.loader import RubricThresholds, anchor_text
from presenceai.schemas.rubric import Condition, Rubric

_OPS = {">=": "≥", "<=": "≤"}


def _condition(c: Condition, t: RubricThresholds) -> str:
    if c.threshold is None:
        return f"`{c.measure}` = yes"
    return f"`{c.measure}` {_OPS[c.op]} {t.values[c.threshold]:g} (`{c.threshold}`)"


def review_markdown(rubric: Rubric, t: RubricThresholds) -> str:
    title = rubric.id.upper().split("_")[0]
    out = [
        f"# {title} rubric anchors: draft for review",
        "",
        f"Rubric `{rubric.id}` version {rubric.version}, status **{rubric.status}**. "
        f"Thresholds: **{t.status}**, decided in {t.decided_in}.",
        "",
        "> Generated by `uv run python scripts/render_rubric_review.py` from "
        f"`resources/rubrics/{rubric.id}.yaml` and `configs/rubric.yaml`. Do not edit by hand.",
        "",
        "## How to read this draft",
        "",
        "- Five dimensions follow the AAC&U VALUE Oral Communication rubric, each with four "
        "levels: " + ", ".join(f"{n} {rubric.scale[n]}" for n in (4, 3, 2, 1)) + ".",
        "- Every anchor describes **observable behaviour with a number**. A level is reached when "
        "all of its conditions hold; the dimension gets the highest level reached; level 1 is the "
        "default.",
        "- A measure that cannot be computed (camera off, no time limit, Arabic content) is left "
        "out of the conditions and never counts against the speaker. A dimension with no "
        "measurable condition is reported as not measurable.",
        "- Skill score for the adaptive engine: y = (level − 1) / 3, so 0, 0.33, 0.67, 1.",
        "- **Every number is proposed.** Numbers from the plan (FINAL_04) are the opening 20 %, "
        "the closing 15 % and the first 2 sentences; all others are first proposals for a "
        "2–3 minute talk.",
        '- "Left out" lists the parts of the VALUE wording that no rule can observe. They are '
        "not scored by rules.",
        "",
    ]
    for d in rubric.dimensions:
        out += [
            f"## {d.name}",
            "",
            f"VALUE dimension: {d.value_dimension}. Feeds the skills: "
            + ", ".join(f"`{s}`" for s in d.skills)
            + ".",
            "",
            "| Level | Anchor (observable) | Conditions |",
            "|---|---|---|",
        ]
        for a in d.levels:
            conds = "<br>".join(_condition(c, t) for c in a.conditions) or "default"
            out.append(f"| {a.level} {rubric.scale[a.level]} | {anchor_text(a, t)} | {conds} |")
        if d.left_out:
            out += ["", "Left out (not observable by rules): " + "; ".join(d.left_out) + "."]
        out.append("")
    out += [
        "## Measures",
        "",
        "| Measure | Status | Needs | Languages | Description |",
        "|---|---|---|---|---|",
    ]
    for key, m in rubric.measures.items():
        status = m.status if m.planned_in is None else f"planned ({m.planned_in})"
        langs = ", ".join(m.languages)
        out.append(f"| `{key}` | {status} | {m.requires} | {langs} | {m.description} |")
    out += [
        "",
        "## Questions for the reviewer",
        "",
        "1. Do the anchors keep the meaning of each VALUE dimension, given what is left out?",
        "2. Are the proposed numbers reasonable for a 2–3 minute student presentation?",
        "3. Should any left-out part be judged by a language model with a quoted transcript span "
        "(only with the user's consent, ADR 0017)?",
        "",
        "## Source and licence",
        "",
        rubric.attribution,
        "",
        f"Source copy: {rubric.source.copy_url} (SHA-256 `{rubric.source.copy_sha256}`).",
    ]
    if rubric.source.note:
        out += ["", rubric.source.note]
    return "\n".join(out) + "\n"
